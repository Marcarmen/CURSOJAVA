public class ModificaciondeArreglos {
    /*MÉTODO MAIN PRINCIPAL*/

    public static void main(String[] args) {
        //DEFINIMOS LA VARIABLLE ENTEROS
        //INDICANDO PRINCIPALMENTE LA VARIABLE
        var enteros = new int [5];

        //EMPEZAMOS A MODIFICAR LOS ELEMENTOS DE NUESTRO ARREGLO
        enteros [0]=11;
        enteros [1]=12;
        enteros [2]=13;



    }
}
